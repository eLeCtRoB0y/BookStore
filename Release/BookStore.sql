-- =====================================================================
-- База данных: BookStore (книжный магазин «ЧитайГород»)
-- СУБД: SQLite 3. Схема в 3НФ, ссылочная целостность через FOREIGN KEY.
-- Запуск: sqlite3 BookStore.db < BookStore.sql
