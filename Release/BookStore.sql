PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS OrderItem;
DROP TABLE IF EXISTS CustomerOrder;
DROP TABLE IF EXISTS OrderStatus;
DROP TABLE IF EXISTS PickupPoint;
DROP TABLE IF EXISTS Product;
DROP TABLE IF EXISTS Unit;
DROP TABLE IF EXISTS Supplier;
DROP TABLE IF EXISTS Manufacturer;
DROP TABLE IF EXISTS Category;
DROP TABLE IF EXISTS AppUser;
DROP TABLE IF EXISTS Role;

CREATE TABLE Role (
    RoleId   INTEGER PRIMARY KEY,
    RoleName TEXT NOT NULL UNIQUE
);

CREATE TABLE AppUser (
    UserId   INTEGER PRIMARY KEY,
    RoleId   INTEGER NOT NULL REFERENCES Role(RoleId) ON UPDATE CASCADE ON DELETE RESTRICT,
    FullName TEXT NOT NULL,
    Login    TEXT NOT NULL UNIQUE,
    Password TEXT NOT NULL
);

CREATE TABLE Category (
    CategoryId   INTEGER PRIMARY KEY,
    CategoryName TEXT NOT NULL UNIQUE
);

CREATE TABLE Manufacturer (
    ManufacturerId   INTEGER PRIMARY KEY,
    ManufacturerName TEXT NOT NULL UNIQUE
);

CREATE TABLE Supplier (
    SupplierId   INTEGER PRIMARY KEY,
    SupplierName TEXT NOT NULL UNIQUE
);

CREATE TABLE Unit (
    UnitId   INTEGER PRIMARY KEY,
    UnitName TEXT NOT NULL UNIQUE
);

CREATE TABLE Product (
    ProductId      INTEGER PRIMARY KEY,
    Article        TEXT    NOT NULL UNIQUE,
    ProductName    TEXT    NOT NULL,
    UnitId         INTEGER NOT NULL REFERENCES Unit(UnitId) ON UPDATE CASCADE ON DELETE RESTRICT,
    Price          REAL    NOT NULL CHECK (Price >= 0),
    SupplierId     INTEGER NOT NULL REFERENCES Supplier(SupplierId) ON UPDATE CASCADE ON DELETE RESTRICT,
    ManufacturerId INTEGER NOT NULL REFERENCES Manufacturer(ManufacturerId) ON UPDATE CASCADE ON DELETE RESTRICT,
    CategoryId     INTEGER NOT NULL REFERENCES Category(CategoryId) ON UPDATE CASCADE ON DELETE RESTRICT,
    Discount       INTEGER NOT NULL DEFAULT 0 CHECK (Discount BETWEEN 0 AND 100),
    StockQuantity  INTEGER NOT NULL DEFAULT 0 CHECK (StockQuantity >= 0),
    Description    TEXT,
    PhotoPath      TEXT
);

CREATE TABLE PickupPoint (
    PickupPointId INTEGER PRIMARY KEY,
    Address       TEXT NOT NULL UNIQUE
);

CREATE TABLE OrderStatus (
    OrderStatusId INTEGER PRIMARY KEY,
    StatusName    TEXT NOT NULL UNIQUE
);

CREATE TABLE CustomerOrder (
    OrderId       INTEGER PRIMARY KEY,
    OrderDate     TEXT    NOT NULL,
    DeliveryDate  TEXT    NOT NULL,
    PickupPointId INTEGER NOT NULL REFERENCES PickupPoint(PickupPointId) ON UPDATE CASCADE ON DELETE RESTRICT,
    UserId        INTEGER NOT NULL REFERENCES AppUser(UserId) ON UPDATE CASCADE ON DELETE RESTRICT,
    ReceiveCode   INTEGER NOT NULL,
    OrderStatusId INTEGER NOT NULL REFERENCES OrderStatus(OrderStatusId) ON UPDATE CASCADE ON DELETE RESTRICT,
    CHECK (DeliveryDate >= OrderDate)
);

CREATE TABLE OrderItem (
    OrderId   INTEGER NOT NULL REFERENCES CustomerOrder(OrderId) ON UPDATE CASCADE ON DELETE CASCADE,
    ProductId INTEGER NOT NULL REFERENCES Product(ProductId) ON UPDATE CASCADE ON DELETE RESTRICT,
    Quantity  INTEGER NOT NULL CHECK (Quantity > 0),
    PRIMARY KEY (OrderId, ProductId)
);

